export const ALL_PRODUCTS = EXTENDED_PRODUCTS_DATA;

/**
 * Finds a product by ID or slug, case-insensitively.
 */
export function getProductById(idOrSlug: string): ProductItem | undefined {
  if (!idOrSlug) return undefined;
  const target = decodeURIComponent(idOrSlug).toLowerCase().trim();

  // Try direct match
  const found = ALL_PRODUCTS.find((p) => {
    const pId = p.id.toLowerCase();
    const pSlug = (p.slug || "").toLowerCase();
    const pName = p.name.toLowerCase().replace(/[^a-z0-9]/g, "");
    const cleanTarget = target.replace(/^(prod-)/, "").replace(/[^a-z0-9]/g, "");

    return (
      pId === target ||
      pSlug === target ||
      pId.replace(/^prod-/, "") === cleanTarget ||
      pName === cleanTarget
    );
  });

  return found || ALL_PRODUCTS[0]; // fallback to first product if none found
}

/**
 * Returns 4 similar products based on category or default leaders
 */
export function getSimilarProducts(currentProduct: ProductItem): ProductItem[] {
  const sameCat = ALL_PRODUCTS.filter(
    (p) => p.id !== currentProduct.id && p.category === currentProduct.category
  );

  if (sameCat.length >= 4) {
    return sameCat.slice(0, 4);
  }

  const others = ALL_PRODUCTS.filter(
    (p) => p.id !== currentProduct.id && !sameCat.some((m) => m.id === p.id)
  );

  return [...sameCat, ...others].slice(0, 4);
}
